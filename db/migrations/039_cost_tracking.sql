-- 039_cost_tracking.sql
--
-- A minimal `firms` table, and `llm_calls`: one row per vendor call.
--
-- RUN BY HAND, in numeric order, BEFORE deploying the code that writes to it.
-- The code survives the table being absent -- recording failures are logged and
-- dropped, never raised into the work being recorded -- but every call made
-- before this runs is spend nobody will ever be able to attribute.
--
-- ── WHY A FIRMS TABLE NOW, WITH ONE ROW ─────────────────────────────────────
--
-- Attribution cannot be added after the fact. A call recorded today without a
-- firm can never be told which firm it belonged to, so the column has to exist
-- from the first row. This is deliberately NOT multi-tenancy: nothing moves out
-- of the PER_FIRM settings, and matters, clients and staff carry no firm yet.
-- It is the smallest thing a foreign key can point at.
--
-- ── WHY TOKENS AND NOT DOLLARS ───────────────────────────────────────────────
--
-- The ledger stores what the vendor COUNTED. Price is applied when a report is
-- run, from a rate table with effective dates (a later migration). Prices get
-- entered late and corrected; a cost frozen onto the row at write time would be
-- wrong forever, while tokens are a fact that never changes.
--
-- ── NULL IS NOT ZERO ─────────────────────────────────────────────────────────
--
-- Every token column is nullable, and NULL means "the vendor did not tell us" --
-- a call that timed out before any response, or a vendor that reports no cache
-- figure. Zero means the vendor said zero. A report that summed NULL as zero
-- would understate spend and look complete.

begin;

-- ── firms ────────────────────────────────────────────────────────────────────

create table if not exists firms (
    id          integer     generated by default as identity primary key,
    name        text        not null,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz
);

-- The one firm that exists. Explicit id so every default below can name it.
-- RENAME IT to the firm's real name after running this; the migration cannot
-- read FIRM_NAME from the environment.
insert into firms (id, name) values (1, 'Default firm')
    on conflict (id) do nothing;

-- An explicit id does not advance the identity sequence, so the next insert
-- would try id 1 again and collide.
select setval(pg_get_serial_sequence('firms', 'id'),
              greatest(1, (select max(id) from firms)));

-- ── llm_calls ────────────────────────────────────────────────────────────────

create table if not exists llm_calls (
    id                          bigint      generated always as identity primary key,

    -- When the call STARTED, set by the application. Recording is written
    -- asynchronously, so insert time can lag the call by seconds.
    occurred_at                 timestamptz not null,

    -- ATTRIBUTION. Only firm_id is a foreign key, and deliberately so: the rest
    -- must OUTLIVE what they point at. A matter deleted next year was still
    -- paid for this year, and a cost record that vanished or went NULL with it
    -- would make the books disagree with the invoice. Same reasoning as
    -- transactions.category_rule_id.
    firm_id                     integer     not null default 1 references firms (id),
    staff_id                    integer,
    matter_id                   integer,
    -- The signed-in identity of a web request. Recorded rather than resolved
    -- to staff_id at call time, which would cost a database round trip on
    -- every LLM call; join staff.supabase_uid when reporting.
    auth_uid                    text,
    -- What started the work: 'job', 'request', 'crm', 'crm_lead', or
    -- 'unattributed'. The last is not an error -- it is spend that reached the
    -- model from somewhere no scope was set, and it is recorded so the gap is
    -- visible rather than silently missing from the totals.
    source_type                 text        not null,
    -- The job id, 'POST /api/v1/billing/parse', a CRM step name, a lead session.
    source_id                   text,

    -- WHAT WAS CALLED
    profile                     text        not null,
    call_type                   text        not null check (call_type in ('text', 'vision')),
    vendor                      text        not null,
    model                       text        not null,
    -- 1 is the preferred candidate; above 1 means the chain fell through.
    chain_position              integer     not null,
    outcome                     text        not null check (outcome in ('succeeded', 'failed')),
    -- Exception class only, never the message: a message can quote the prompt.
    error_class                 text,
    duration_ms                 integer,

    -- NORMALIZED USAGE. Vendors disagree about what "input tokens" means --
    -- Anthropic's excludes cached tokens, OpenAI's and Gemini's include them --
    -- and Gemini reports its thinking tokens outside its output count although
    -- they are billed as output. These columns are the reconciled figures; see
    -- app/services/llm_usage.py for the mapping per vendor.
    input_uncached_tokens       integer,
    input_cache_read_tokens     integer,
    input_cache_write_tokens    integer,
    -- Everything billed at the output rate, reasoning included.
    output_tokens               integer,
    -- The reasoning share of output_tokens, where the vendor reports it.
    -- Informational: it is already counted in output_tokens.
    reasoning_tokens            integer,
    -- The vendor's usage object verbatim. If a mapping above is ever found to
    -- be wrong, the normalized columns can be recomputed from this.
    usage_raw                   jsonb,

    created_at                  timestamptz not null default now()
);

create index if not exists idx_llm_calls_firm_time    on llm_calls (firm_id, occurred_at);
create index if not exists idx_llm_calls_matter_time  on llm_calls (matter_id, occurred_at)
    where matter_id is not null;
create index if not exists idx_llm_calls_staff_time   on llm_calls (staff_id, occurred_at)
    where staff_id is not null;
create index if not exists idx_llm_calls_source       on llm_calls (source_type, source_id);

-- ── Immutable, like audit_log ────────────────────────────────────────────────
--
-- A cost ledger that can be edited is not evidence of cost. Corrections belong
-- in the rate table, which is where a price changes; the counts never do.
-- DELETE is left possible on purpose: a retention policy may one day need it,
-- and that is a decision for then.

create or replace function deny_llm_calls_update()
returns trigger
language plpgsql as $$
begin
    raise exception 'llm_calls rows are immutable. id=%', old.id;
end;
$$;

drop trigger if exists trg_llm_calls_no_update on llm_calls;
create trigger trg_llm_calls_no_update
    before update on llm_calls
    for each row execute function deny_llm_calls_update();

commit;
